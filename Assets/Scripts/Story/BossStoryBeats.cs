    /// <summary>当前大关号（1..GrandCountOf）。取不到真值就报错并回退到第 1 座，口径与 Get() 的占位一致。</summary>
    static int CurrentGrand()
    {
        var cm = ChapterManager.Instance;
        if (cm == null)
        {
            Debug.LogError("[BossStoryBeats] ChapterManager 缺失，无法定位大关");
            return 1;
        }
        int total = ActProgressionDefs.GrandCountOf(cm.currentChapter);
        if (cm.currentGrand < 1 || cm.currentGrand > total)
        {
            Debug.LogError("[BossStoryBeats] 大关号越界: " + cm.currentGrand);
            return 1;
        }
        return cm.currentGrand;
    }

    /// <summary>本章三选一的三句回答（调用方会洗牌，按钮顺序与战意对应每场都变）。</summary>
    public static string[] GetBlessingAnswers(int chapter)
    {
        int idx = chapter - 1;
        if (idx < 0 || idx >= Answers.Length)
        {
            Debug.LogError("[BossStoryBeats] 未登记的章节回答: " + chapter);
            return (string[])Answers[0].Clone();   // 同 Get() 口径：认不出就报错，不静默跳过
        }
        int grand = CurrentGrand();
        if (grand == 1) return (string[])Answers[idx].Clone();
        int vi = grand - 2;
        if (vi < 0 || vi >= GrandVariants[idx].Length)
        {
            Debug.LogError("[BossStoryBeats] 未登记的大关回答: " + chapter + "-" + grand);
            return (string[])Answers[idx].Clone();
        }
        string[] v = GrandVariants[idx][vi];
        return new[] { v[1], v[2], v[3] };
    }

    static Line Get(int chapter)
    {
        int idx = chapter - 1;
        if (idx < 0 || idx >= Lines.Length)
        {
            Debug.LogError("[BossStoryBeats] 未登记的章节 boss 线: " + chapter);
            return Lines[0];   // 占位：认不出就报错，不静默跳过
        }
        return Lines[idx];
    }

    /// <summary>把本章 boss 线两句引子追加到播放链（三选一之前）。grand≥2 时先加一句本关开场旁白。</summary>
    public static void AppendIntro(List<StoryBeat> beats, int chapter)
    {
        int idx = chapter - 1;
        if (idx < 0 || idx >= Lines.Length)
        {
            Debug.LogError("[BossStoryBeats] 未登记的章节 boss 线: " + chapter);
            idx = 0;   // 占位：认不出就报错，不静默跳过
        }
        int grand = CurrentGrand();
        if (grand >= 2)
        {
            int vi = grand - 2;
            if (vi < 0 || vi >= GrandVariants[idx].Length)
                Debug.LogError("[BossStoryBeats] 未登记的大关开场: " + chapter + "-" + grand);
            else
                beats.Add(StoryDirector.Narration(GrandVariants[idx][vi][0]));
        }
        var l = Get(chapter);
        beats.Add(StoryDirector.Narration(l.Narration));
        // 【2026-11-17 主线饱满化】守门 boss 开口一句，用旁白引述『』（无专属立绘，不建名牌），
        // 把"又来一队/前面几队没回去/带头的姑娘"这条主线暗线经 boss 之口递进点出。
        // 用 Narration 不加任何立绘/名牌：boss 只是话音，避免与玩家立绘同框错配。
        beats.Add(StoryDirector.Narration(l.BossLine));
        // 与三选一那个 beat 同构（speaker=-1 + 左侧玩家），别用 Solo：
        // Solo 会把立绘居中，接在左侧玩家框后面会跳一下；整段保持同一个框。
        beats.Add(new StoryBeat
        {
            leftName = "你",
            leftPortraitId = StoryPortraits.Player,
            speaker = -1,
            text = l.YouLine
        });
    }

    /// <summary>三选一引导语：按章收口外号，接住上面两句引子。</summary>
    public static string GetBlessingLead(int chapter) => Get(chapter).Lead;
