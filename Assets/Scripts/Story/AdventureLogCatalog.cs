    public struct AchEntry
    {
        public string Id;
        public string Name;
        public string Category;
        public string Unlock;
        public string Reward;
        public string Desc;
    }

    public struct WorldEntry
    {
        public string Id;
        public string Name;
        public string Category;
        public string Unlock;
        public string Desc;
        public string Flavor;
    }

    public struct StoryEntry
    {
        public string Id;
        public string Title;
        public string Unlock;
        public string Summary;
        public string Extra;
    }

