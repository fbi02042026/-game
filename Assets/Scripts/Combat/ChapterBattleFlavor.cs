{
    /// <summary>下标 [chapter-1]；对应主线第 1~8 章。</summary>
    static readonly string[][] Lines = new string[][]
    {
        // 第 1 章 暮影森林（样本、斜光、下一层是墓园）
        new[] { "公会的样本瓶比剑贵，打怪悠着点。", "这林子的光是斜的，照不到地上。", "下一层是墓园？我靴子先冷了。" },
        // 第 2 章 幽冥墓园（碑、七块、甜风）
        new[] { "碑上的名字只剩一半，另一半呢？", "一共七块碑……呸，不数了不数了。", "这里的风是甜的，甜得不对劲。" },
        // 第 3 章 翡翠秘境（纸条、新漆路标、朝前的脚印）
        new[] { "又捡到纸条了：「不要停下」。写的人腿真快。", "路标是新漆的——有人一直走在咱们前面。", "脚印全往深处去，没有一个回头。" },
        // 第 4 章 晨曦草原（风车刻度、铁锈味）
        new[] { "风车一圈三年，替谁数日子呢？", "风里混着铁锈味，远处在打仗？", "齿轮上刻着刻度……回头再细看。" },
        // 第 5 章 海岛遗迹（连号补给箱、撬开的舱门、退潮）
        new[] { "这批补给箱编号连着号，跟咱们那批一样。", "船长舱的门是从里面撬开的，有点渗人。", "潮水退一次，露出来的东西新一次。" },
