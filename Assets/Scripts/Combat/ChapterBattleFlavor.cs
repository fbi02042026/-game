        new[] { "石壁上的字一层压一层，全是同一句。", "最上面那行没写完：「如果你读到这——」", "越往下走，石头越像在喘气。" },
        // 第 7 章 赤焰炼狱（热不是火、不烫的灰烬）
        new[] { "这里的热不是火，火抗符没用。", "灰烬落在肩上不烫——这才吓人。", "前面就是最深处了，债和答案都在等。" },
        // 第 8 章 永霜雪境（不化的雪、白线、认剑的雪）
        new[] { "雪落下来就不化了，落在血上也一样。", "看到那条白线没有？这就是尽头。", "剑刃上的雪化了——它认得这把剑。" },
    };

    /// <summary>
    /// 取当前战斗的章节风味台词；不该说（非主线 Normal / 章节越界）返回 null，由调用方回落个人台词。
    /// 章节取 bm.RunStats.Chapter（战后剧情结算同一真源）。
    /// </summary>
    public static string PickForCurrentBattle(BattleManager bm)
    {
        if (bm == null || bm.Mode == null || bm.Mode.Id != BattleModeId.Normal) return null;
        int ch = Mathf.Clamp(bm.RunStats.Chapter, 1, Lines.Length);
        var pool = Lines[ch - 1];
        return pool[Random.Range(0, pool.Length)];
    }
}
