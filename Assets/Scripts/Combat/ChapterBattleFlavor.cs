/// 但不是重要的」）。每章 3 句，内容 = 本章线索/引言的回声（纸条、碑、风车、刻字、雪），
/// 纯氛围、不承载任何玩法关键信息；只有主线 Normal 关会说，活动副本/无限裂隙/引导局不插嘴。
/// 说话人 = 随机存活佣兵（挂接点 MercBattleBanter，四成概率走这里，其余照旧说个人台词）。
/// 文案走 C# 常量（项目约定）。想改只动这张表，一处一句。
/// </summary>
