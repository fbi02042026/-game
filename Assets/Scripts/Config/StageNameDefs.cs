/// 主线关卡名（2026-10-29 主人拍板「给每个关卡加个名字，1-1 有点单调」）。
/// · 唯一出口 = <see cref="Get"/>；消费点：冒险详情面板标题（AdventureUI.Detail）「1-3  关名」。
/// · 关卡槽位牌仍只显示编号（牌面 125px 放不下关名，主人确认口径）。
/// · 每章 5 关的命名节奏：入口 → 深入 → 第 3 关小高潮（银箱关）→ 逼近 → 第 5 关 Boss 老巢（金箱关）；
///   意象与各章地图名/引言对齐（GameConfig.GetChapterMapName / ChapterStoryBeats.ChapterQuote）。
/// · 文案走 C# 常量（项目约定）；名字 ≤5 汉字（主人命名偏好 ≤7，标题框 209px 宽留余量）。
/// 想改某个名字只动这张表，一处一名。
/// </summary>
public static class StageNameDefs
{
    /// <summary>下标 [chapter-1][stage-1]；一章 5 关。</summary>
    static readonly string[][] Names = new string[][]
    {
        // 第 1 章 暮影森林（公会新人试炼场，裂隙第一层；「林子里的光是斜的，照不到地上」）
