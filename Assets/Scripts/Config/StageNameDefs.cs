        new[] { "藤门岔路", "新漆路标", "绞缠林道", "塌门古道", "秘境树心" },
        // 第 4 章 晨曦草原（风车还在转，没人记得它替谁数日子）
        new[] { "风车田埂", "长草车影", "老磨坊仓", "无名风口", "老风车塔" },
        // 第 5 章 海岛遗迹（「潮水每天退一次，退一次就露出一点旧东西」）
        // 5-5 对齐 Boss 沉船船长（Sea-BossA）与 N5 搁浅补给船主场景
        new[] { "三岔滩头", "半沉回廊", "潮退石阶", "沉箱暗仓", "沉船长舱" },
        // 第 6 章 巨岩深窟（「越往下走，石壁上的字越多」；底下压着诸神留下的东西）
        // 6-5 = N6 沉座揭底后的地名回收（6-5 必在战前剧情 N6 之后才显示，不剧透）
