        new[] { "林口小道", "斜光林地", "兽夹谷地", "废弃营地", "食人花巢" },
        // 第 2 章 幽冥墓园（「碑上的名字，大多只剩一半」）
        // 2-4 对齐 N2「石头却是新的——有人提前把碑做好了」，用「新土」不剧透七碑数字
        new[] { "断碑小径", "半名碑林", "白骨回廊", "新土坟场", "主墓大厅" },
        // 第 3 章 翡翠秘境（「藤蔓比路还老」，有人一直翻新路标）
