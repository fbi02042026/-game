///   ① **局内 · 抽奖币 SlotCoin**（本文件管的就是这套）
///      —— 抽奖花的就是它（一抽 80）。
///      来源（**就这三条，别处不再有第二个给币口径**）：
///        ① 每局携带 240 + 初始资金天赋每级 80
///        ② 每关通关 **+100**（战斗内；金币本不发 —— `IBattleMode.GrantsRunCoins`）
///        ③ 抽中「金币」安慰奖（一抽价 × 0.5 = 40）
///      ⚠ 引导局**没有任何中途补贴**（「每两波 +100」那条已于 2026-10-05 删除，见三·补②）。
///      **局末清零**（回城 / 死亡 / 撤离）；**选「进下一章」不清零**，币跟着带过去
