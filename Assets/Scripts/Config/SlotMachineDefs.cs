    /// <summary>「技能」类被抽中的权重。</summary>
    public const int CATEGORY_WEIGHT_SKILL = 5;
    /// <summary>「装备」类被抽中的权重。</summary>
    public const int CATEGORY_WEIGHT_EQUIP = 3;
    /// <summary>「佣兵」类被抽中的权重（<b>主人要求：必须低于装备</b>）。</summary>
    public const int CATEGORY_WEIGHT_MERC = 2;

    /// <summary>类型的抽中权重 —— 唯一出口，随机与概率公示都问它。</summary>
    public static int CategoryWeight(DraftCategory c)
    {
        switch (c)
        {
            case DraftCategory.Merc: return CATEGORY_WEIGHT_MERC;
            case DraftCategory.Equip: return CATEGORY_WEIGHT_EQUIP;
            default: return CATEGORY_WEIGHT_SKILL;
        }
    }

